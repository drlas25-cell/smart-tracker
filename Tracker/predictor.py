import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor

TARGET = "hours_spent"       # عمود الهدف في مشروعك
CAT_COLS = ["priority", "status", "platform"]      # عموداتك الفئوية - عدّلها


def prepare_data(df):
    """يجهّز X و y: صفوف نظيفة + أعمدة فئوية مشفّرة."""
    if df.empty:
        return pd.DataFrame(), pd.Series()

    # تنظيف صفوف الهدف الناقصة
    df_clean = df.dropna(subset=[TARGET])

    # فصل المتغير المستهدف
    y = df_clean[TARGET]

    # تشفير الأعمدة الفئوية واختيار الميزات
    X = pd.get_dummies(df_clean[CAT_COLS], drop_first=True)

    return X, y


def train_model(X, y, kind="linear"):
    """يدرب ويرجّع الموديل - نوع التدريب حسب kind"""
    if kind == "linear":
        model = LinearRegression()
    elif kind == "tree":
        model = DecisionTreeRegressor(random_state=42)
    else:
        raise ValueError(f"Unknown model kind: {kind}")

    model.fit(X, y)
    return model

