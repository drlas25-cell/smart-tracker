import os
import matplotlib.pyplot as plt
import seaborn as sns

FIG_DIR = "reports/figures"


def chart_distribution(df, col="hours_spent", name="distribution.png"):
    """يولد رسم بياني لتوزيع عمود رقمي واحد (مثل ساعات العمل)."""
    os.makedirs(FIG_DIR, exist_ok=True)
    plt.figure(figsize=(8, 5))
    plt.hist(df[col].dropna(), bins=15, color='skyblue', edgecolor='black')
    plt.title(f"Distribution of {col}")
    plt.xlabel(col)
    plt.ylabel("Frequency")
    plt.grid(True, linestyle='--', alpha=0.5)
    save_path = os.path.join(FIG_DIR, name)
    plt.savefig(save_path)
    plt.close()
    print(f"Saved distribution chart to: {save_path}")


def chart_categories(df, x_col="priority", y_col="hours_spent", name="categories.png"):
    """يولد رسم بياني لمتوسط القيم الرقمية لكل فئة (مثل متوسط الساعات لكل مستوى أولوية)."""
    os.makedirs(FIG_DIR, exist_ok=True)
    plt.figure(figsize=(8, 5))
    grouped = df.groupby(x_col)[y_col].mean().reset_index()
    plt.bar(grouped[x_col], grouped[y_col], color='salmon', edgecolor='black')
    plt.title(f"Average {y_col} by {x_col}")
    plt.xlabel(x_col)
    plt.ylabel(f"Average {y_col}")
    plt.grid(axis='y', linestyle='--', alpha=0.5)
    save_path = os.path.join(FIG_DIR, name)
    plt.savefig(save_path)
    plt.close()
    print(f"Saved categories chart to: {save_path}")


def chart_relationship(df, x_col="issue_id", y_col="hours_spent", name="relationship.png"):
    """يوضح العلاقة بين متغيرين (مثل رقم المشكلة والساعات المستغرقة للحرب)."""
    os.makedirs(FIG_DIR, exist_ok=True)
    plt.figure(figsize=(8, 5))
    plt.scatter(df[x_col], df[y_col], color='purple', alpha=0.6)
    plt.title(f"Relationship between {x_col} and {y_col}")
    plt.xlabel(x_col)
    plt.ylabel(y_col)
    plt.grid(True, linestyle='--', alpha=0.5)
    save_path = os.path.join(FIG_DIR, name)
    plt.savefig(save_path)
    plt.close()
    print(f"Saved relationship chart to: {save_path}")


def chart_correlation(df, name="heatmap.png"):
    """يرسم مصفوفة الارتباط للأعمدة الرقمية لمعرفة العلاقات المتداخلة."""
    os.makedirs(FIG_DIR, exist_ok=True)
    plt.figure(figsize=(6, 5))
    corr_matrix = df.corr(numeric_only=True)
    sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', fmt=".2f", linewidths=0.5)
    plt.title("Correlation Heatmap")
    save_path = os.path.join(FIG_DIR, name)
    plt.savefig(save_path)
    plt.close()
    print(f"Saved heatmap to: {save_path}")

